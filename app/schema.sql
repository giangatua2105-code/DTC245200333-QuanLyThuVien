CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE,
 password TEXT NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'reader' CHECK(role IN ('reader','librarian','admin')),
 phone VARCHAR(20) NOT NULL DEFAULT '', address VARCHAR(200) NOT NULL DEFAULT '', active BOOLEAN NOT NULL DEFAULT true,
 version INT NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS categories(id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS books(id SERIAL PRIMARY KEY, title VARCHAR(200) NOT NULL, author VARCHAR(100) NOT NULL,
 category_id INT NOT NULL REFERENCES categories(id), quantity INT NOT NULL CHECK(quantity>=0));
CREATE TABLE IF NOT EXISTS loans(id SERIAL PRIMARY KEY, user_id INT NOT NULL REFERENCES users(id), book_id INT NOT NULL REFERENCES books(id),
 borrowed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), due_date DATE NOT NULL,
 returned_at TIMESTAMPTZ, CHECK(due_date >= (borrowed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date),
 CHECK(returned_at IS NULL OR returned_at>=borrowed_at));
CREATE UNIQUE INDEX IF NOT EXISTS one_active_book ON loans(user_id,book_id) WHERE returned_at IS NULL;
CREATE TABLE IF NOT EXISTS sessions(sid TEXT PRIMARY KEY, data JSONB NOT NULL, expires TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS resets(hash TEXT PRIMARY KEY, user_id INT NOT NULL REFERENCES users(id), expires TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS rate_limits(key TEXT PRIMARY KEY, count INT NOT NULL DEFAULT 1, expires TIMESTAMPTZ NOT NULL);
